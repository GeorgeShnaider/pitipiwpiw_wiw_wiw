// =============================================================================
//  i2c_bus.h — короткие транзакции I2C поверх Wire с ограниченным временем.
//
//  Правила, чтобы отсутствующий или зависший датчик не держал loop():
//   - перед каждой транзакцией проверяется, что SDA и SCL в 1 (busIdle());
//     если линия прижата к 0, транзакция не запускается вовсе;
//   - аппаратный таймаут бита I2C уменьшен с максимума ядра (0xFFFFF тактов
//     APB ≈ 13 мс) до I2C_HW_BIT_TIMEOUT_US;
//   - чтение регистров делается двумя транзакциями (запись адреса со STOP,
//     затем чтение), без повторного старта: при NACK на записи Wire.requestFrom
//     не вызывается и ядро не печатает «[E][Wire.cpp:499]».
// =============================================================================
#pragma once

#include <stddef.h>
#include <stdint.h>

// Аппаратный таймаут одного бита — I2C_HW_BIT_TIMEOUT_US из config.h.
// Бит на 400 кГц — 2.5 мкс; MS5837 и MPU-6050 не растягивают SCL.

namespace i2cbus {

void begin();

// SDA и SCL в логической 1 (шина свободна)
bool busIdle();

// Проба адреса: START + адрес + STOP без данных. true — устройство ответило ACK.
bool probe(uint8_t addr);

// Запись одного байта-команды (MS5837: reset, конверсия, чтение АЦП)
bool writeCmd(uint8_t addr, uint8_t cmd);
// Запись регистра
bool writeReg(uint8_t addr, uint8_t reg, uint8_t value);
// Запись адреса регистра/команды (со STOP), затем чтение n байт
bool readRegs(uint8_t addr, uint8_t reg, uint8_t *buf, uint8_t n);

}  // namespace i2cbus
